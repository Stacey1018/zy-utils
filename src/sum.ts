
/**
 * The function `sum` takes two numbers as input and returns their sum.
 * @param {number} a - The parameter `a` is a number.
 * @param {number} b - The parameter `b` in the `sum` function is a number that is being added to the
 * parameter `a` to calculate the sum.
 * @returns The sum of the two input numbers, `a` and `b`, is being returned.
 */
const sum = (a: number, b: number): number => {
  // console.log(a);
  return a + b
}
export { sum }
